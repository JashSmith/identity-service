#!/usr/bin/env python3
"""Generates the console's dark-mode Radzen variables.

The console always loads Radzen's light "material" theme and switches to dark with CSS only
(html[data-theme="dark"], or "system" + prefers-color-scheme), so the choice needs no reload and
never flashes. This script copies every variable whose value differs between material.css and
material-dark.css into those selectors. Rerun it after upgrading Radzen.Blazor:

    python scripts/generate-radzen-dark-css.py
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/Hosts/Identity.Admin/wwwroot/css/radzen-dark.css"


def radzen_version() -> str:
    props = ET.parse(ROOT / "Directory.Packages.props")
    for item in props.iter("PackageVersion"):
        if item.get("Include") == "Radzen.Blazor":
            return item.get("Version")
    sys.exit("Radzen.Blazor is not in Directory.Packages.props")


def root_variables(css: str) -> dict[str, str]:
    start = css.find("--rz-white:")
    block = css[css.rfind("{", 0, start) + 1: css.find("}", start)]
    pairs = (decl.split(":", 1) for decl in block.split(";") if ":" in decl)
    return {name.strip(): value.strip() for name, value in pairs}


def main() -> None:
    version = radzen_version()
    css_dir = pathlib.Path.home() / ".nuget/packages/radzen.blazor" / version / "staticwebassets/css"
    light = root_variables((css_dir / "material.css").read_text(encoding="utf-8-sig"))
    dark = root_variables((css_dir / "material-dark.css").read_text(encoding="utf-8-sig"))
    changed = [(name, dark[name]) for name in light if dark.get(name) != light[name]]
    if not changed:
        sys.exit("No differing variables found; did the Radzen theme format change?")
    body = "".join(f"  {name}: {value};\n" for name, value in changed if re.match(r"^--rz-[a-z0-9-]+$", name))
    OUTPUT.write_text(
        f"/* Generated by scripts/generate-radzen-dark-css.py from Radzen.Blazor {version} (material-dark). Do not edit. */\n"
        f'html[data-theme="dark"] {{\n{body}}}\n\n'
        f'@media (prefers-color-scheme: dark) {{\nhtml[data-theme="system"] {{\n{body}}}\n}}\n',
        encoding="utf-8", newline="\n")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(changed)} variables")


if __name__ == "__main__":
    main()
